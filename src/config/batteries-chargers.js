// Helper to filter items by bike compatibility
export function filterByBikeCompatibility(items, bikeTag) {
  if (!bikeTag || bikeTag === 'All Bikes') return items;
  return items.filter((item) => {
    if (!item.fitment || !Array.isArray(item.fitment)) return false;
    return item.fitment.some((tag) =>
      tag.toLowerCase().includes(bikeTag.toLowerCase()) ||
      bikeTag.toLowerCase().includes(tag.toLowerCase())
    );
  });
}
